/**
 * Единая точка округления денег во всём модуле — до копеек.
 * Промежуточные итоги округляются на каждом шаге, чтобы строка формулы на экране
 * и итог в таблице никогда не расходились на копейку.
 */
export function roundKopecks(value: number): number {
  return Math.round((value + Number.EPSILON) * 100) / 100;
}
